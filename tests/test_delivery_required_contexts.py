"""The checks a generated delivery must pass include CI and every Gate Python shard runtime.

stranske/Orchestrator#530, a dev-tool pin bump generated by Workflows, merged through Maint 71 on
2026-10-11 while `verify.py` had failed on its head. This repo has no branch protection, so the only
check Maint 71 required was `Gate / gate`, and the Gate does not run `ci.yml`. Main went red for
every open PR until #519 re-measured the lint baseline.

`.github/config/required-contexts.json` is the consumer's declaration that Maint 71 reads from main
(stranske/Workflows#3847): it will not merge a generated delivery while a declared check has failed.
A declared name that matches no job is not an error there. Maint 71 reports it as "never started,
not enforced" and moves on, so it cannot hold deliveries forever. The Gate summary therefore also
requires one artifact receipt per shard/runtime and fails when any is missing; the declaration and
the local artifact latch cover different failure modes.

The list must EQUAL the set of `ci.yml` jobs that run on a pull request plus all twelve Gate
shard/runtime checks. A CI job missing from it is CI a delivery can merge around, while a Gate
shard missing from the workflow, the declaration, or the summary receipts must be a local failure.
"""

from __future__ import annotations

import importlib.util
import json
import re
import sys
from pathlib import Path

import paths

ROOT = paths.REPO_ROOT
DECLARATION = ROOT / ".github" / "config" / "required-contexts.json"
CI = ROOT / ".github" / "workflows" / "ci.yml"
GATE = ROOT / ".github" / "workflows" / "pr-00-gate.yml"
GATE_SUMMARY_PATH = ROOT / ".github" / "scripts" / "gate_summary.py"

JOB_HEADER = re.compile(r"^  ([A-Za-z0-9_-]+):\s*$")
JOB_FIELD = re.compile(r"^    (name|if):\s*(.+?)\s*$")
PUSH_CLAUSE = "github.event_name == 'push'"


def _is_push_only(condition: str) -> bool:
    """True only when a top-level `&&` clause is exactly the push test; `push || pull_request` is not."""
    clauses = [clause.strip().strip("()").strip() for clause in condition.split("&&")]
    return PUSH_CLAUSE in clauses


def _ci_jobs() -> dict[str, dict[str, str]]:
    """Each job under `jobs:` with its `name:` and `if:`, read from the committed workflow."""
    jobs: dict[str, dict[str, str]] = {}
    current = None
    in_jobs = False
    for line in CI.read_text(encoding="utf-8").splitlines():
        if line.startswith("jobs:"):
            in_jobs = True
            continue
        if not in_jobs:
            continue
        if line and not line.startswith(" ") and not line.startswith("#"):
            break
        header = JOB_HEADER.match(line)
        if header:
            current = jobs.setdefault(header.group(1), {})
            continue
        field = JOB_FIELD.match(line)
        if current is not None and field:
            current[field.group(1)] = field.group(2)
        shard_values = re.match(r"^        shard: (\[.*\])$", line)
        if current is not None and shard_values:
            current["shards"] = shard_values.group(1)
    return jobs


def _job_check_names(job_id: str, fields: dict[str, str]) -> set[str]:
    name = fields.get("name", job_id)
    if "shards" in fields:
        assert "${{ matrix.shard }}" in name, fields
        return {name.replace("${{ matrix.shard }}", str(i)) for i in json.loads(fields["shards"])}
    assert "${{" not in name, f"unexpanded check name: {name}"
    return {name}


def _pull_request_check_names() -> set[str]:
    """The check-run name of every job that runs on a pull request.

    A job with no `name:` posts its id as the check name. A job whose `if:` requires a push never
    runs on a pull request.
    """
    names = set()
    for job_id, fields in _ci_jobs().items():
        if _is_push_only(fields.get("if", "")):
            continue
        names.update(_job_check_names(job_id, fields))
    return names


def _declared() -> list[str]:
    payload = json.loads(DECLARATION.read_text(encoding="utf-8"))
    names = payload["required_contexts"]
    assert isinstance(names, list) and all(isinstance(name, str) for name in names), names
    return names


def _gate_python_shard_contexts() -> set[str]:
    text = GATE.read_text(encoding="utf-8")
    assert "name: python ci shard ${{ matrix.shard }}/6" in text
    assert 'python-versions: \'["3.13", "3.14"]\'' in text
    assert "matrix: ${{ fromJSON(needs.detect.outputs.python_ci_matrix) }}" in text
    assert "pytest_args: ${{ matrix.pytest_args }}" in text
    assert "artifact-prefix: ${{ matrix.artifact_prefix }}" in text
    return {
        f"python ci shard {shard}/6 / python {runtime}"
        for shard in range(1, 7)
        for runtime in ("3.13", "3.14")
    }


def _load_gate_summary():
    spec = importlib.util.spec_from_file_location("gate_summary_issue_969", GATE_SUMMARY_PATH)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def _write_shard_summary(root: Path, shard: int, runtime: str, attempt: int = 1) -> Path:
    artifact = root / "downloads" / f"gate-shard-{shard}-coverage-{runtime}-{attempt}"
    summary = artifact / "artifacts" / "coverage" / "runtimes" / runtime / "summary.json"
    summary.parent.mkdir(parents=True)
    summary.write_text(
        json.dumps(
            {
                "python_version": runtime,
                "checks": {
                    "tests": {"outcome": "success"},
                    "coverage_minimum": {"outcome": "skipped"},
                },
            }
        ),
        encoding="utf-8",
    )
    return summary


def test_ci_runs_on_pull_requests():
    text = CI.read_text(encoding="utf-8")
    assert re.search(r"(?m)^on:\s*$", text), "ci.yml has no `on:` block"
    assert re.search(
        r"(?m)^  pull_request:", text
    ), "ci.yml no longer runs on pull_request, so no declared check can ever run on a delivery"


def test_the_job_reader_sees_every_job():
    # Counted against an independent count, never truthiness: a reader that found nothing would
    # make the equality below vacuous. Every job declares exactly one `runs-on:` or `uses:`.
    jobs = _ci_jobs()
    executors = re.findall(r"(?m)^    (?:runs-on|uses):", CI.read_text(encoding="utf-8"))
    assert len(jobs) == len(executors), sorted(jobs)
    push_only = {job_id for job_id, f in jobs.items() if _is_push_only(f.get("if", ""))}
    assert len(_pull_request_check_names()) == sum(
        len(_job_check_names(job_id, fields))
        for job_id, fields in jobs.items()
        if job_id not in push_only
    )


def test_shard_contexts_name_every_matrix_child():
    assert _job_check_names(
        "shards", {"name": "shard ${{ matrix.shard }}/3", "shards": "[1, 2, 3]"}
    ) == {
        "shard 1/3",
        "shard 2/3",
        "shard 3/3",
    }


def test_only_a_push_only_condition_removes_a_job():
    assert _is_push_only("github.event_name == 'push' && github.ref == 'refs/heads/main'")
    assert not _is_push_only("github.event_name == 'push' || github.event_name == 'pull_request'")
    assert not _is_push_only("")


def test_declaration_equals_pull_request_ci_and_gate_python_shards():
    declared = _declared()
    assert len(declared) == len(set(declared)), f"duplicate names in {DECLARATION.name}"
    expected = _pull_request_check_names() | _gate_python_shard_contexts()
    missing = sorted(expected - set(declared))
    unknown = sorted(set(declared) - expected)
    assert not missing, (
        f"ci.yml pull-request jobs not declared, so a generated delivery can merge with them red: "
        f"{missing}. Add them to {DECLARATION.relative_to(ROOT)}."
    )
    assert not unknown, (
        f"declared names that match no CI or Gate pull-request job, which Maint 71 would report as "
        f"never started and not enforce: {unknown}"
    )


def test_gate_summary_requires_every_shard_runtime_receipt(tmp_path):
    gate_summary = _load_gate_summary()
    summaries = {
        (shard, runtime): _write_shard_summary(tmp_path, shard, runtime)
        for shard in range(1, 7)
        for runtime in ("3.13", "3.14")
    }
    context = gate_summary.SummaryContext(
        doc_only=False,
        run_core=True,
        reason="code_changes",
        python_result="success",
        docker_result="skipped",
        docker_changed=False,
        artifacts_root=tmp_path,
        summary_path=None,
        output_path=None,
        python_required=True,
        combined_coverage_status="complete",
        combined_coverage_percent=81.25,
    )

    green = gate_summary.summarize(context)
    assert green.state == "success"
    assert green.description == "All Gate checks succeeded."
    assert (
        "- Python shard artifacts: ✅ all 6 shards reported for Python 3.13 and 3.14."
        in green.lines
    )
    assert "- Combined coverage: ✅ 81.25% from CI verify.py aggregate." in green.lines

    summaries[(4, "3.14")].unlink()
    missing = gate_summary.summarize(context)
    assert missing.state == "failure"
    assert missing.description == "Python CI artifacts missing: shard 4/6 (Python 3.14)."
    assert "- Python shard artifacts: ❌ missing shard 4/6 (Python 3.14)." in missing.lines


def test_gate_summary_never_turns_missing_combined_coverage_into_zero_or_pass(tmp_path):
    gate_summary = _load_gate_summary()
    for shard in range(1, 7):
        for runtime in ("3.13", "3.14"):
            _write_shard_summary(tmp_path, shard, runtime)
    context = gate_summary.SummaryContext(
        doc_only=False,
        run_core=True,
        reason="code_changes",
        python_result="success",
        docker_result="skipped",
        docker_changed=False,
        artifacts_root=tmp_path,
        summary_path=None,
        output_path=None,
        python_required=True,
        combined_coverage_status="missing-or-invalid-combined-trend",
    )

    result = gate_summary.summarize(context)
    line = next(line for line in result.lines if line.startswith("- Combined coverage:"))
    assert "UNKNOWN" in line
    assert "missing-or-invalid-combined-trend" in line
    assert "✅" not in line
    assert re.search(r"\b\d+(?:\.\d+)?%", line) is None


def test_gate_summary_uses_the_newest_rerun_receipt(tmp_path):
    gate_summary = _load_gate_summary()
    for shard in range(1, 7):
        for runtime in ("3.13", "3.14"):
            _write_shard_summary(tmp_path, shard, runtime)
    newest = _write_shard_summary(tmp_path, 2, "3.14", attempt=2)
    payload = json.loads(newest.read_text(encoding="utf-8"))
    payload["checks"]["tests"]["outcome"] = "success"
    newest.write_text(json.dumps(payload), encoding="utf-8")

    records = gate_summary._load_summary_records(tmp_path)
    shard_two = [
        record
        for record in records
        if record.get("shard") == 2 and record.get("python_version") == "3.14"
    ]
    assert len(shard_two) == 1 and shard_two[0]["run_attempt"] == 2


def test_gate_coverage_reads_and_republishes_only_the_exact_head_combined_measurement():
    text = GATE.read_text(encoding="utf-8")
    assert "workflow_id: 'ci.yml'" in text
    assert "head_sha: headSha" in text
    assert "candidate.head_sha === headSha" in text
    assert "run-id: ${{ steps.combined_coverage.outputs.run_id }}" in text
    assert "root = Path('gate_artifacts/combined')" in text
    assert "root / 'gate-coverage' / 'coverage.json'" in text
    assert "root / 'gate-coverage-trend' / 'coverage-trend.json'" in text
    assert "combined-payload-trend-mismatch" in text
    assert "no percentage or pass is inferred" in text
    assert "path: gate-combined/coverage.json" in text
    assert "path: gate-combined/coverage-trend.json" in text
